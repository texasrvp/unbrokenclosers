(function () {
  var CFG = window.UC_CONFIG || {};
  var skoolJoin = CFG.skoolJoinUrl || "programs.html#circle";
  function circlePriceLine() {
    var p = CFG.circlePrice || { regular: 79, founding: 49, foundingSpots: 10 };
    return "$" + p.regular + " a month. The first " + p.foundingSpots + " founding members pay $" + p.founding + " a month, locked for life. Cancel any time.";
  }

  var root = document.getElementById("assessment");
  if (!root) return;
  var O = window.UC_OBJECTIONS;

  var ITEMS = [
    ["scarcity", "Talking about price or payments makes me uncomfortable."],
    ["planted", "If I worked at a better store or had better leads, I’d sell a lot more."],
    ["rejection", "When a customer says no, it feels personal."],
    ["promises", "I sometimes promise customers things I don’t follow through on."],
    ["discipline", "My effort goes up and down with my mood."],
    ["selfbelief", "I set goals I know I can hit instead of ones that stretch me."],
    ["belonging", "I feel like customers judge me before I say a word."],
    ["responsibility", "When I miss a goal, it’s usually because of things outside my control."],
    ["showingup", "I’d rather struggle alone than ask for help."],
    ["tracking", "I don’t know my closing ratio or my other numbers."],
    ["comparison", "When I look at the sales board, I feel behind everyone else."],
    ["commission", "I size up customers by how much I’ll make on them."],
    ["purpose", "After a decent month, I tend to coast."],
    ["circle", "The people I spend the most time with at work complain more than they sell."],
    ["resilience", "A bad day can stay with me for days."],
    ["connection", "I decide whether a customer is worth my time within the first minute."],
    ["scarcity", "Deep down, I don’t believe people like me make big money."],
    ["planted", "I’m always looking for the next opportunity instead of mastering this one."],
    ["belonging", "Around successful people, I feel like I don’t belong."],
    ["responsibility", "I wait for my manager or the company to fix the things holding me back."],
    ["rejection", "I sometimes avoid asking for the sale so I don’t hear no."],
    ["commission", "I’ve pushed a product because it paid more, not because it fit."],
    ["showingup", "I expect people to let me down eventually."],
    ["circle", "I feel uncomfortable around the top performers on my team."],
    ["comparison", "Another rep’s big month makes me feel worse about mine."],
    ["promises", "Follow-up calls I said I’d make often slip through the cracks."],
    ["discipline", "I start strong on goals and fade after a few weeks."],
    ["connection", "After the sale, I rarely stay in touch with customers."],
    ["resilience", "After a slow week, I think about quitting."],
    ["selfbelief", "When I do well, I tell myself it was luck."],
    ["purpose", "I’m not sure who or what I’m really working for anymore."],
    ["tracking", "I give up on new habits before they have a chance to work."]
  ];
  var SCALE = ["Not me at all", "Rarely", "Sometimes", "Often", "That’s me"];
  var KEY = "uc_assessment_v2";

  var answers = [];
  var i = 0;
  try {
    var saved = JSON.parse(localStorage.getItem(KEY) || "null");
    if (saved && saved.answers && saved.i > 0 && saved.i < ITEMS.length) { answers = saved.answers; i = saved.i; }
  } catch (e) {}
  function save() { try { localStorage.setItem(KEY, JSON.stringify({ answers: answers, i: i })); } catch (e) {} }
  function clearSave() { try { localStorage.removeItem(KEY); } catch (e) {} }
  var stage = root.querySelector(".as-stage");
  var bar = root.querySelector(".as-bar span");
  var count = root.querySelector(".as-count");

  function esc(s) { var d = document.createElement("div"); d.textContent = s; return d.innerHTML; }

  function renderItem() {
    var item = ITEMS[i];
    count.textContent = "Statement " + (i + 1) + " of " + ITEMS.length;
    bar.style.width = (i / ITEMS.length * 100) + "%";
    stage.innerHTML =
      '<p class="as-statement">' + esc(item[1]) + "</p>" +
      '<div class="as-scale" role="group" aria-label="How true is this for you?">' +
      SCALE.map(function (label, n) {
        var pressed = answers[i] === n + 1 ? "true" : "false";
        return '<button type="button" class="as-opt" aria-pressed="' + pressed + '" data-v="' + (n + 1) + '"><b>' + (n + 1) + "</b><span>" + label + "</span></button>";
      }).join("") + "</div>" +
      '<div class="as-nav">' + (i > 0 ? '<button type="button" class="btn btn-ghost as-back">Back</button>' : "") +
      (i > 0 ? '<button type="button" class="as-reset">Start over</button>' : "") +
      '<span class="as-keys">Tip: press 1 to 5 on your keyboard</span></div>';
    stage.querySelectorAll(".as-opt").forEach(function (b) {
      b.addEventListener("click", function () {
        answers[i] = +b.getAttribute("data-v");
        stage.querySelectorAll(".as-opt").forEach(function (x) { x.setAttribute("aria-pressed", x === b ? "true" : "false"); });
        setTimeout(function () {
          i++;
          save();
          if (i < ITEMS.length) renderItem(); else { clearSave(); finish(); }
        }, 180);
      });
    });
    var back = stage.querySelector(".as-back");
    if (back) back.addEventListener("click", function () { i--; save(); renderItem(); });
    var reset = stage.querySelector(".as-reset");
    if (reset) reset.addEventListener("click", function () { answers = []; i = 0; clearSave(); renderItem(); });
    var focusTarget = stage.querySelector('.as-opt[aria-pressed="true"]') || stage.querySelector(".as-opt");
    if (i > 0 && focusTarget) focusTarget.focus();
  }

  function finish() {
    bar.style.width = "100%";
    var scores = {};
    Object.keys(O).forEach(function (k) { scores[k] = 0; });
    ITEMS.forEach(function (item, n) { scores[item[0]] += answers[n] || 0; });
    var ranked = Object.keys(scores).sort(function (a, b) { return scores[b] - scores[a]; });
    var top = ranked.filter(function (k) { return scores[k] >= 6; }).slice(0, 3);
    var strong = top.length === 0;
    if (strong) top = ranked.slice(0, 1);

    count.textContent = "Your results";
    var html = '<div class="as-results">';
    html += strong
      ? "<h2>You’re Standing on Solid Ground</h2><p class=\"as-lede\">None of the sixteen inner objections scored high for you. Here’s the one to keep an eye on, because the floor tests everyone eventually.</p>"
      : "<h2>What’s Been Holding You Back</h2><p class=\"as-lede\">Every salesperson has objections of their own, the ones no customer ever says out loud. These are yours, starting with the strongest.</p>";

    top.forEach(function (k, n) {
      var o = O[k];
      html += '<article class="as-card">' +
        '<div class="as-card-head"><span class="as-rank">' + (n + 1) + "</span><div><h3>" + esc(o.name) + '</h3><p class="as-says">' + esc(o.says) + "</p></div></div>" +
        '<div class="as-card-body">' +
        "<h4>How It Shows Up on the Floor</h4><p>" + esc(o.floor) + "</p>" +
        '<h4>From the Book: ' + esc(o.chapter) + "</h4><p>" + esc(o.story) + "</p>" +
        '<h4>Your First Step This Week</h4><p class="as-step">' + esc(o.step) + "</p>" +
        '<p class="as-more"><a href="inner-objections.html#' + k + '">Read more in the Inner Objections Library</a></p>' +
        "</div></article>";
    });

    html += '<p class="note as-note">This is coaching, not counseling. If one of these touches a deep hurt, like grief, trauma or something from childhood, talking with a licensed counselor is a strong move. <a href="support.html">Find support</a>.</p>';
    html += '<h3 class="as-all-title">All Sixteen, From Strongest to Weakest</h3><div class="as-all">';
    ranked.forEach(function (k) {
      var pct = Math.round((scores[k] - 2) / 8 * 100);
      html += '<div class="as-row"><span>' + esc(O[k].name) + '</span><span class="as-meter" aria-hidden="true"><i style="width:' + Math.max(4, pct) + '%"></i></span><b>' + scores[k] + "/10</b></div>";
    });
    html += "</div>";

    html += '<div class="as-next">' +
      "<h3>Your First Lesson Is Waiting: " + esc(O[top[0]].name) + "</h3>" +
      "<p>In the Closer’s Circle, “" + esc(O[top[0]].name) + "” is a full lesson from the chapter " + esc(O[top[0]].chapter) + ", with a drill, a Soft Pitch practice round and live coaching on Tuesday calls. Bring these results to your first call and LJ will build your plan around them.</p>" +
      '<p class="small">' + circlePriceLine() + '</p>' +
      '<div class="btn-row"><a class="btn btn-stripe" href="' + esc(skoolJoin) + '" target="_blank" rel="noopener" data-track="join_circle">Join the Closer’s Circle on Skool</a>' +
      '<a class="btn btn-ghost" href="book.html?session=circle">Talk with LJ first</a>' +
      '<button type="button" class="btn btn-ghost as-restart">Retake the assessment</button></div>' +
      '<div class="as-tools"><button type="button" class="as-tool as-print">Print or save as PDF</button><button type="button" class="as-tool as-copy">Copy my results</button></div></div>';
    html += "</div>";
    stage.innerHTML = html;

    // Optional results form
    var form = document.getElementById("assessment-form");
    if (form) {
      form.hidden = false;
      form.querySelector('[name="top_areas"]').value = top.map(function (k) { return O[k].name; }).join(", ");
    }
    stage.querySelector(".as-print").addEventListener("click", function () { window.print(); });
    stage.querySelector(".as-copy").addEventListener("click", function (e) {
      var text = "My Unbroken Assessment results:\n" + top.map(function (k, n) { return (n + 1) + ". " + O[k].name + " \u2014 " + O[k].step; }).join("\n") +
        "\n\nTake it free: https://unbrokenclosers.com/assessment.html";
      if (window.UC_copy) window.UC_copy(text, e.currentTarget);
    });
    stage.querySelector(".as-restart").addEventListener("click", function () {
      answers = []; i = 0; if (form) form.hidden = true; renderItem();
    });
    if (window.UC_track) window.UC_track("assessment_complete", { top: top.join(",") });
    var h = stage.querySelector("h2"); h.setAttribute("tabindex", "-1"); h.focus();
  }

  document.addEventListener("keydown", function (e) {
    if (e.target.matches("input, textarea, select")) return;
    var opt = stage.querySelector('.as-opt[data-v="' + e.key + '"]');
    if (opt) { e.preventDefault(); opt.click(); }
  });

  renderItem();
})();
